import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';
import 'package:firebase_core/firebase_core.dart';
import 'l10n/app_locale_controller.dart';
import 'l10n/app_localizations.dart';
import 'pages/main_shell.dart';
import 'services/favorites_controller.dart';
import 'theme/app_colors.dart';
import 'firebase_options.dart'; // generated by flutterfire

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await FavoritesController.instance.load();
  runApp(const MyApp());
}

class MyApp extends StatefulWidget {
  const MyApp({super.key});

  @override
  State<MyApp> createState() => _MyAppState();
}

class _MyAppState extends State<MyApp> {
  final AppLocaleController _localeController = AppLocaleController();

  @override
  void dispose() {
    _localeController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return buildAppLocaleScope(
      controller: _localeController,
      child: ValueListenableBuilder<Locale>(
        valueListenable: _localeController,
        builder: (context, locale, _) {
          return buildFavoritesScope(
            controller: FavoritesController.instance,
            child: MaterialApp(
              debugShowCheckedModeBanner: false,
              locale: locale,
              supportedLocales: AppLocalizations.supportedLocales,
              localizationsDelegates: const [
                AppLocalizationsDelegate(),
                GlobalMaterialLocalizations.delegate,
                GlobalWidgetsLocalizations.delegate,
                GlobalCupertinoLocalizations.delegate,
              ],
              themeMode: ThemeMode.light,
              theme: ThemeData(
                brightness: Brightness.light,
                scaffoldBackgroundColor: AppColors.background,
                colorScheme: const ColorScheme.light(
                  primary: AppColors.primary,
                  surface: AppColors.card,
                  onPrimary: Colors.white,
                  onSurface: AppColors.textPrimary,
                ),
                appBarTheme: const AppBarTheme(
                  backgroundColor: AppColors.background,
                  foregroundColor: AppColors.textPrimary,
                  elevation: 0,
                ),
                cardColor: AppColors.card,
                textTheme: const TextTheme(
                  bodyLarge: TextStyle(color: AppColors.textPrimary),
                  bodyMedium: TextStyle(color: AppColors.textPrimary),
                  titleLarge: TextStyle(color: AppColors.textPrimary),
                ),
              ),
              home: const MainShell(),
            ),
          );
        },
      ),
    );
  }
}
